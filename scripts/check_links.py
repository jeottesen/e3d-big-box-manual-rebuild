#!/usr/bin/env python3
"""List and test the external links in the manual.

  list              read the HTML in docs/, add every external link to notes/link-status.json, and write
                    notes/external-links.md (a table of every link, its text, the pages it is on and its status)
  archive           infer which hosts are down (three or more 503s, none working) and look up a Wayback Machine copy
                    of every dead link that has none (needs the network; `check` does this at the end)
  check [--host H] [--recheck]
                    test links and record the result in notes/link-status.json; needs the network
                    (--host limits it to one host; --recheck tests links that already have a result)

build.py reads notes/link-status.json: a link whose status is "dead" keeps its text in the manual and is labelled
"(dead link)", with a link to the Wayback Machine copy if there is one. Statuses:

  untested  not tested yet            ok       answered normally
  dead      gone: 404/410, the name does not resolve, the connection is refused, a removed YouTube video
  unknown   answered but needs a human to look: 401/403/429, a server error, a timeout, a redirect to the home page
  blocked   not tested: the sandbox's proxy does not allow the host (this is never reported as dead)

A status with "by": "maintainer" was set by hand and is only re-tested with --recheck.
Be polite: one request at a time with a pause. Run:  python3 -I scripts/check_links.py list | check
"""
import datetime, html, json, os, re, socket, ssl, sys, time, urllib.error, urllib.parse, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.environ.get('BIGBOX_SITE', f'{ROOT}/docs')
STATUS = os.environ.get('BIGBOX_LINKS', f'{ROOT}/notes/link-status.json')
REPORT = f'{ROOT}/notes/external-links.md'
UA = 'bigbox-manual-linkcheck/1.0 (documentation project; one request at a time)'
DELAY = 1.0

def load(): return json.load(open(STATUS)) if os.path.exists(STATUS) else {}
def save(d): json.dump(dict(sorted(d.items())), open(STATUS, 'w'), indent=1, ensure_ascii=False); open(STATUS, 'a').write('\n')

def find_links():
    """url -> {text, pages} for every external link in the built pages (a link already labelled dead is not a link any more)."""
    found = {}
    for f in sorted(os.listdir(SITE)):
        if not f.endswith('.html') or f in ('index.html', 'manual.html'): continue
        page = f[:-5]
        for m in re.finditer(r'<a\b[^>]*?\bhref="(https?://[^"]+)"[^>]*>(.*?)</a>', open(f'{SITE}/{f}').read(), re.S):
            url = html.unescape(m.group(1))
            if urllib.parse.urlparse(url).netloc.lower() == 'wiki.e3d-online.com': continue
            text = ' '.join(html.unescape(re.sub(r'<[^>]+>', '', m.group(2))).split())
            e = found.setdefault(url, {'text': text, 'pages': []})
            if page not in e['pages']: e['pages'].append(page)
    return found

def cmd_list():
    status = load()
    for url, info in find_links().items():
        e = status.setdefault(url, {'status': 'untested'})
        e['text'], e['pages'] = info['text'], sorted(set(e.get('pages', [])) | set(info['pages']))
    save(status)
    cell = lambda s: s.replace('|', '\\|')
    shown = lambda t: f'`{cell(t)}`' if re.match(r'https?://', t) else cell(t)   # link text that is itself a URL: code, not a bare URL
    rows = []
    for url, e in sorted(status.items(), key=lambda kv: (urllib.parse.urlparse(kv[0]).netloc.lower(), kv[0])):
        arch = f' ([archived copy]({e["archived"]}))' if e.get('archived') else ''
        rows.append(f'| {e["status"]}{arch} | `{cell(url)}` | {shown(e.get("text", "")[:70])} | {cell(", ".join(p.replace("_", " ") for p in e.get("pages", [])))} |')
    counts = {}
    for e in status.values(): counts[e['status']] = counts.get(e['status'], 0) + 1
    open(REPORT, 'w').write('# External links\n\nEvery external link in the manual, with the result of testing it. '
        'Generated by `scripts/check_links.py`; a link marked dead is labelled "(dead link)" in the manual.\n\n'
        + ', '.join(f'{n} {k}' for k, n in sorted(counts.items())) + f' ({len(status)} links).\n\n'
        '| Status | Link | Text | Pages |\n| --- | --- | --- | --- |\n' + '\n'.join(rows) + '\n')
    print(f'{len(status)} links: ' + ', '.join(f'{n} {k}' for k, n in sorted(counts.items())) + f'\nwrote {STATUS} and {REPORT}')

def probe(url):
    """(status, code or None, note, final url) for one link."""
    host = urllib.parse.urlparse(url).netloc.lower()
    if host in ('youtu.be', 'www.youtube.com', 'youtube.com'):   # a removed video still answers 200 on its page; oEmbed says 404
        test = 'https://www.youtube.com/oembed?format=json&url=' + urllib.parse.quote(url, safe='')
    else: test = url
    try:
        req = urllib.request.Request(test, headers={'User-Agent': UA, 'Accept': '*/*'})
        with urllib.request.urlopen(req, timeout=25, context=ssl.create_default_context()) as r:
            r.read(2048)
            final, code = r.geturl(), r.status
        if test is url and final != url:
            a, b = urllib.parse.urlparse(url), urllib.parse.urlparse(final)
            if b.path in ('', '/') and a.path not in ('', '/'): return 'unknown', code, 'redirects to the home page', final
            return 'ok', code, 'redirects', final
        return 'ok', code, '', ''
    except urllib.error.HTTPError as e:
        if e.headers.get('X-Proxy-Error'): return 'blocked', None, 'the sandbox proxy does not allow this host', ''   # the proxy answered, not the site
        if e.code in (404, 410): return 'dead', e.code, 'not found' if test is url else 'video unavailable', ''
        if test is not url and e.code in (400, 401): return 'dead', e.code, 'video unavailable or private', ''
        return 'unknown', e.code, f'HTTP {e.code}', ''
    except urllib.error.URLError as e:
        reason = e.reason
        if 'tunnel connection failed' in str(reason).lower() or 'proxy' in str(reason).lower(): return 'blocked', None, 'the sandbox proxy does not allow this host', ''
        if isinstance(reason, socket.gaierror): return 'dead', None, 'the name does not resolve', ''
        if isinstance(reason, ConnectionRefusedError): return 'dead', None, 'connection refused', ''
        return 'unknown', None, f'{type(reason).__name__}: {reason}', ''
    except (socket.timeout, TimeoutError): return 'unknown', None, 'timed out', ''
    except Exception as e: return 'unknown', None, f'{type(e).__name__}: {e}', ''

def wayback_copy(url):
    """URL of the newest Wayback Machine capture (status 200) of a dead link, or None. Uses the capture index, then the availability API."""
    def fetch(api):
        with urllib.request.urlopen(urllib.request.Request(api, headers={'User-Agent': UA}), timeout=45) as r: return r.read().decode('utf-8', 'replace')
    try:
        row = fetch('https://web.archive.org/cdx/search/cdx?output=txt&fl=timestamp,original&filter=statuscode:200&limit=-1&url=' + urllib.parse.quote(url, safe='')).split()
        if len(row) == 2 and re.match(r'\d{14}$', row[0]): return f'https://web.archive.org/web/{row[0]}/{row[1].replace(":80", "", 1)}'
    except Exception: pass
    try:
        snap = json.loads(fetch('https://archive.org/wayback/available?url=' + urllib.parse.quote(url, safe=''))).get('archived_snapshots', {}).get('closest')
        return snap['url'].replace('http://', 'https://', 1) if snap and snap.get('available') and str(snap.get('status')) == '200' else None
    except Exception: return None

def infer_down_hosts(status):
    """A host where at least three links answered 503 and none worked is down: its other links are dead too."""
    hosts = {}
    for u, e in status.items(): hosts.setdefault(urllib.parse.urlparse(u).netloc.lower(), []).append(e)
    for host, es in hosts.items():
        if sum(e['status'] == 'unknown' and e.get('code') == 503 for e in es) >= 3 and not any(e['status'] == 'ok' for e in es):
            for e in es:
                if e['status'] in ('unknown', 'blocked', 'untested') and e.get('by') != 'maintainer':
                    e.update(status='dead', by='script', note=f'{host} answers 503 for every link tested; the site is down')
                    print(f'  {host}: marked dead (every link answers 503)', flush=True)

def fill_archived(status):
    for url, e in status.items():
        if e['status'] == 'dead' and not e.get('archived'):
            arch = wayback_copy(url)
            if arch: e['archived'] = arch; print(f'  archived copy: {url[:80]}', flush=True)
            time.sleep(DELAY)

def cmd_check(host, recheck):
    status = load()
    if not status: sys.exit('No links yet. Run `check_links.py list` first.')
    todo = [u for u, e in status.items()
            if (not host or urllib.parse.urlparse(u).netloc.lower() == host)
            and (recheck or (e['status'] in ('untested', 'unknown', 'blocked') and e.get('by') != 'maintainer'))]
    print(f'testing {len(todo)} of {len(status)} links', flush=True)
    blocked_hosts = {}
    for n, url in enumerate(todo, 1):
        h = urllib.parse.urlparse(url).netloc.lower()
        if blocked_hosts.get(h, 0) >= 3: continue   # the proxy refuses this host: stop asking
        time.sleep(DELAY)
        st, code, note, final = probe(url)
        blocked_hosts[h] = blocked_hosts.get(h, 0) + 1 if st == 'blocked' else 0
        e = status[url]
        e.update(status=st, checked=datetime.date.today().isoformat(), by='script')
        for k, v in (('code', code), ('note', note), ('final', final)):
            if v: e[k] = v
            else: e.pop(k, None)
        print(f'[{n}/{len(todo)}] {st:8} {code or "":4} {url[:90]}  {note}', flush=True)
        save(status)
    cmd_archive()

def cmd_archive():
    """Infer which hosts are down, then look up Wayback copies of every dead link that has none."""
    status = load()
    infer_down_hosts(status); save(status)
    fill_archived(status); save(status)
    cmd_list()

if __name__ == '__main__':
    args = sys.argv[1:]
    if args[:1] == ['list']: cmd_list()
    elif args[:1] == ['archive']: cmd_archive()
    elif args[:1] == ['check']:
        host = args[args.index('--host') + 1].lower() if '--host' in args else None
        cmd_check(host, '--recheck' in args)
    else: sys.exit(__doc__)
